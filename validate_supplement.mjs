import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {queries,supplementaryQueries,classificationCheck,boundaryChecks} from './research_data.mjs';
const base=path.dirname(fileURLToPath(import.meta.url));
const lines=(await fs.readFile(path.join(base,'records_builders.tsv'),'utf8')).trim().split('\n');
const headers=lines.shift().split('\t');
const rows=lines.map(l=>Object.fromEntries(l.split('\t').map((x,i)=>[headers[i],x])));
const appKey=headers.find(x=>/application/.test(x));
if(!appKey) throw Error('Application column not found: '+headers.join(','));
const original=new Set(rows.map(r=>r[appKey].replace(/\D/g,'')));
const classIds=new Set(classificationCheck.map(r=>r[0]));
const newIds=[...classIds].filter(x=>!original.has(x));
const core=rows.filter(r=>r.decision==='액침 포함');
if(original.size!==44 || core.length!==2 || newIds.join()!=='1020170005313')throw Error('Unexpected cohort overlap');
const result={date:'2026-11-08',originalCohort:44,classificationCandidates:4,overlapWithOriginal:3,newCandidates:newIds,combinedUniqueCandidates:45,coreImmersion:2,notes:'Original 44-row workbook unchanged. Q6/Q7 are validation routes. Q8 is exploratory, not a fully adjudicated cohort.',queries:[...queries,...supplementaryQueries],classificationCheck,boundaryChecks};
const out=path.join(base,'outputs/team2_20261108');
await fs.writeFile(path.join(out,'supplementary_validation.json'),JSON.stringify(result,null,2));
await fs.writeFile(path.join(out,'보완검색_검증기록.tsv'),[['query_id','purpose','displayed_results','exact_query','interpretation'],...supplementaryQueries].map(r=>r.join('\t')).join('\n')+'\n');
await fs.writeFile(path.join(out,'IPC_후보_검토.tsv'),[['application','applicant','title','queries','decision','reason'],...classificationCheck].map(r=>r.join('\t')).join('\n')+'\n');
console.log(JSON.stringify({original:original.size,classification:classIds.size,overlap:classIds.size-newIds.length,newIds,core:core.length}));
